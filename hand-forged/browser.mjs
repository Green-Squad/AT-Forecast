import { chromium } from 'playwright';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1280,height:900}});
const page=await context.newPage();const failures=[];
page.on('pageerror',e=>failures.push(e.message));
page.on('response',r=>{if(r.url().includes('/assets/')&&r.status()>=400)failures.push('Asset '+r.status()+' '+r.url());});
await page.goto('http://127.0.0.1:8080/');
if((await page.textContent('body')).includes('Hand-Forged Edition'))throw Error('Unexpected banner');
await page.locator('.state[data-statename=Georgia]').click();
await page.getByRole('link',{name:'Max Epperson Shelter',exact:true}).click();
await page.waitForURL('**/shelters/1');
if(await page.locator('table.pure-table').count()!==7)throw Error('daily/hourly forecasts missing');
fs.mkdirSync('hand-forged/test-results',{recursive:true});
await page.screenshot({path:'hand-forged/test-results/shelter.png',fullPage:true});
await page.goto('http://127.0.0.1:8080/admin/login');
await page.locator('#admin_user_email').fill('admin@handforged.invalid');await page.locator('#admin_user_password').fill('HandForgedDemo!');
await page.locator('input[type=submit]').click();await page.waitForURL('**/admin');
await page.screenshot({path:'hand-forged/test-results/admin.png',fullPage:true});
await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:8080/');
await page.locator('#mileage').fill('10');await page.locator('input[type=submit]').click();await page.waitForURL('**/nearest_shelter?nobo_mile=10');
await page.screenshot({path:'hand-forged/test-results/mobile-shelter.png',fullPage:true});
if(failures.length)throw Error(failures.join('; '));
await browser.close();console.log('PASS original desktop/mobile navigation, forecast tables, working assets and rendered admin login');
